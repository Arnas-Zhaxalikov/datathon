"""Профиль качества данных — Слой 1 ИИ-аналитика.

Не анализирует данные содержательно — считает детерминированные флаги,
которые агент обязан проверить ПЕРЕД тем, как делать содержательное
утверждение. Источник правил: docs/data_notes.md и docs/RULES.md.

Вход:  outputs/aggregates/completeness.csv, outputs/aggregates/m_correlations_2024.csv
Выход: outputs/aggregates/data_quality_flags.json
"""
import json
import os

import pandas as pd

AGG = "outputs/aggregates"
OUT = f"{AGG}/data_quality_flags.json"

sep = lambda t: print("\n" + "=" * 78 + f"\n{t}\n" + "=" * 78)

# ---------------------------------------------------------------------------
# 1. Дрейф схемы между годами — факты, найденные руками в Результате 1,
#    зарегистрированные здесь как структура, которую агент может прочитать.
# ---------------------------------------------------------------------------
sep("1. РЕЕСТР ДРЕЙФА СХЕМЫ")
schema_drift = [
    {
        "table": "1t_god / 1t_kv / 2t",
        "field": "GR1 -> VAL_NUM",
        "years": "2021-2023 -> 2024",
        "effect": "колонка со значением переименована; прямое склеивание годов без ремаппинга даёт NULL",
    },
    {
        "table": "1t_god / 1t_kv / 2t",
        "field": "KATO -> KATO1",
        "years": "2021-2023 -> 2024",
        "effect": "колонка региона переименована",
    },
    {
        "table": "любая региональная",
        "field": "число регионов",
        "years": "17 (2021) -> 20 (2022+)",
        "effect": "реформа 2022: добавлены Абай, Жетісу, Ұлытау; любой региональный ряд 2021-2024 рвётся на этой границе",
    },
    {
        "table": "1t_god / 1t_kv",
        "field": "ОКЭД",
        "years": "2 знака -> 4-5 знаков",
        "effect": "отраслевые коды не сопоставимы между годами без агрегации до 2 знаков",
    },
    {
        "table": "1t_god",
        "field": "число предприятий",
        "years": "70874 -> 77994 -> 83754 -> 52289",
        "effect": "падение 2024 года — смена охвата выгрузки, не экономический процесс",
    },
]
for row in schema_drift:
    print(f"  {row['table']:<20} {row['field']:<24} {row['years']}")

# ---------------------------------------------------------------------------
# 2. Надёжность корреляций — автоматический тег по порогу |r| < 0.1,
#    найденному в Результате 1 (межформенные связи обнулены, а не ослаблены).
# ---------------------------------------------------------------------------
sep("2. НАДЁЖНОСТЬ СВЯЗЕЙ")
NEAR_ZERO = 0.1
SMALL_N = 30

corr = pd.read_csv(f"{AGG}/m_correlations_2024.csv")
corr["reliability"] = corr["pearson_r"].abs().apply(
    lambda r: "near_zero" if r < NEAR_ZERO else "structural"
)
corr["warning"] = corr.apply(
    lambda row: (
        f"связь '{row['pair']}' статистически неотличима от нуля (r={row['pearson_r']}); "
        "формулировка вида 'X растёт с Y' здесь недопустима"
        if row["reliability"] == "near_zero"
        else None
    ),
    axis=1,
)
print(corr[["pair", "n", "pearson_r", "reliability"]].to_string(index=False))

# ---------------------------------------------------------------------------
# 3. Заполненность — таблицы, где пропуски нужно проверять на branching,
#    а не считать ошибкой или трактовать как MCAR.
# ---------------------------------------------------------------------------
sep("3. ЗАПОЛНЕННОСТЬ")
LOW_FILL = 50.0
completeness = pd.read_csv(f"{AGG}/completeness.csv")
low_fill = completeness[completeness["filled_pct"] < LOW_FILL].copy()
low_fill["note"] = "низкая заполненность; проверить branching анкеты перед интерпретацией как пропуска"
print(f"Таблиц с заполненностью < {LOW_FILL}%: {len(low_fill)} из {len(completeness)}")

# ---------------------------------------------------------------------------
# 4. Известные аномалии и ограничения — реестр находок Результата 1,
#    которые агент обязан процитировать при релевантном вопросе.
# ---------------------------------------------------------------------------
sep("4. РЕЕСТР ИЗВЕСТНЫХ АНОМАЛИЙ")
known_anomalies = [
    {
        "id": "almaty_informality",
        "trigger": "вопросы о неформальной занятости в Алматинской области",
        "finding": "доля работающих без договора 4.8% -> 40.7% за год при стабильной базе ответов; "
                   "без этого региона ряд ровный на 3.0%. Похоже на сбой генератора, не на реальный процесс.",
    },
    {
        "id": "savings_rate_miscalibrated",
        "trigger": "вопросы о норме сбережений / балансе доходов и расходов",
        "finding": "расчётная норма сбережений 56.9-66.1% против реальных 10-15% по Казахстану. "
                   "Блоки доходов и расходов в синтетике откалиброваны независимо друг от друга — "
                   "это не экономический вывод, а артефакт генератора.",
        "real_world_prior": "10-15%",
    },
    {
        "id": "no_panel",
        "trigger": "любое утверждение о динамике ОДНОГО домохозяйства между годами",
        "finding": "NOMER перевыдаётся каждый год; совпадение региона между 2023 и 2024 по номеру — 5.4% "
                   "при случайном уровне 5%. Панели нет, возможны только повторные срезы.",
    },
    {
        "id": "understated_standard_errors",
        "trigger": "любое упоминание статистической значимости / p-value",
        "finding": "одна синтетическая таблица без репликаций (указано в README организатора); "
                   "стандартные ошибки занижены, значимость трактуется осторожно.",
    },
    {
        "id": "kcp_no_reference",
        "trigger": "вопросы о зарплате / фонде оплаты труда из форм 1-Т, 2-Т",
        "finding": "нет справочника KCP; попытка вывести среднюю зарплату даёт 47-774 тг/мес по годам "
                   "(бессмысленно). Формы 1-Т/2-Т используются только структурно.",
    },
]
for a in known_anomalies:
    print(f"  [{a['id']}] {a['trigger']}")

# ---------------------------------------------------------------------------
# Сборка профиля
# ---------------------------------------------------------------------------
profile = {
    "schema_drift": schema_drift,
    "correlation_reliability": corr.drop(columns=["warning"]).assign(
        warning=corr["warning"]
    ).to_dict(orient="records"),
    "low_completeness_tables": low_fill.to_dict(orient="records"),
    "known_anomalies": known_anomalies,
    "thresholds": {"near_zero_r": NEAR_ZERO, "small_n": SMALL_N, "low_fill_pct": LOW_FILL},
}

os.makedirs(AGG, exist_ok=True)
with open(OUT, "w", encoding="utf-8") as f:
    json.dump(profile, f, ensure_ascii=False, indent=2)

sep("ГОТОВО")
print(f"Профиль записан в {OUT}")
print(f"  дрейф схемы: {len(schema_drift)} событий")
print(f"  связей помечено near_zero: {(corr['reliability'] == 'near_zero').sum()} из {len(corr)}")
print(f"  таблиц с низкой заполненностью: {len(low_fill)}")
print(f"  известных аномалий: {len(known_anomalies)}")
